def save_state(simulator, path):
    """Store exact event-boundary state, referring to verified estimators by hash."""
    import cloudpickle
    references = {id(model): ("model", name) for name, model in
                  simulator._execution_time_prediction_model_manager._diagnostic_models.items()}
    references.update({id(predictor): ("predictor", role.name)
                       for role, predictor in simulator._predictors.items()})
    references.update({id(type(predictor)): ("predictor_class", role.name)
                       for role, predictor in simulator._predictors.items()})
    references[id(simulator._execution_time_prediction_model_manager)] = ("manager", "shared")
    pools = []
    for scheduler in simulator._global_scheduler._cluster_schedulers.values():
        for replica in scheduler._replica_schedulers.values():
            pool = replica._kv_cache_manager.block_pool
            if any(pool is existing for existing in pools):
                continue
            index = len(pools)
            pools.append(pool)
            references.update({id(block): ("block", index, block.block_id) for block in pool.blocks})
    block_rows = [[(b.block_id, b.ref_cnt, b._block_hash, b._creator_request_id, b.binding_epoch,
                    None if b.prev_free_block is None else b.prev_free_block.block_id,
                    None if b.next_free_block is None else b.next_free_block.block_id)
                   for b in pool.blocks] for pool in pools]

    class Pickler(cloudpickle.CloudPickler):
        def persistent_id(self, obj):
            return references.get(id(obj))

    Pickler.dispatch_table = Pickler.dispatch_table.copy()
    Pickler.dispatch_table[type(threading.Lock())] = lambda _: (threading.Lock, ())
    Pickler.dispatch_table[type(threading.RLock())] = lambda _: (threading.RLock, ())
    keys = ("_global_scheduler", "_event_queue", "_metric_store", "_all_requests",
            "_requests_by_session_id", "_time", "_event_trace", "_clusters")
    with path.open("xb") as stream:
        pickle.dump(block_rows, stream)
        state = {"simulator": {key: getattr(simulator, key) for key in keys},
                  "predictors": {role.name: predictor.__dict__
                                 for role, predictor in simulator._predictors.items()},
                  "counters": {cls.__name__: cls._id for cls in entity_counters()},
                  "iteration_boundary": simulator._diagnostic_iteration_boundary,
                  "pending_stages": {
                      old_id: event._batch_stage
                      for _, event in simulator._event_queue
                      if getattr(event, "_batch_stage", None) is not None
                      and (old_id := id(event._batch_stage)) in
                      simulator._metric_store._pending_frontier_stage_batch_ledger_rows}}
        Pickler(stream).dump(state)


def load_state(simulator, path, output):
    from frontier.kv_cache.kv_cache_block import KVCacheBlock

    models = simulator._execution_time_prediction_model_manager._diagnostic_models
    with path.open("rb") as stream:
        block_rows = pickle.load(stream)
        blocks = [[KVCacheBlock(*row[:5]) for row in pool] for pool in block_rows]
        for pool, rows in zip(blocks, block_rows):
            for block, row in zip(pool, rows):
                block.prev_free_block = None if row[5] is None else pool[row[5]]
                block.next_free_block = None if row[6] is None else pool[row[6]]
        offset = stream.tell()

    class Unpickler(pickle.Unpickler):
        def persistent_load(self, identity):
            if identity[0] == "block":
                return blocks[identity[1]][identity[2]]
            kind, name = identity
            if kind == "model":
                return models[name]
            if kind == "manager":
                return simulator._execution_time_prediction_model_manager
            predictor = next(predictor for role, predictor in simulator._predictors.items()
                             if role.name == name)
            return type(predictor) if kind == "predictor_class" else predictor

    with path.open("rb") as stream:
        stream.seek(offset)
        state = Unpickler(stream).load()
    for role, predictor in simulator._predictors.items():
        stored = state["predictors"][role.name]
        assert vars(stored["_replica_config"]) == vars(predictor._replica_config)
    simulator.__dict__.update(state["simulator"])
    for role, predictor in simulator._predictors.items():
        predictor.__dict__.update(state["predictors"][role.name])
    metrics = simulator._metric_store
    for cls in entity_counters():
        cls._id = state["counters"][cls.__name__]
    stages = state["pending_stages"]
    assert set(stages) == set(metrics._pending_frontier_stage_batch_ledger_rows)
    metrics._pending_frontier_stage_batch_ledger_rows = {
        id(stages[old]): row for old, row in metrics._pending_frontier_stage_batch_ledger_rows.items()}
    metrics._pending_frontier_stage_batch_ledger_row_keys = {
        key: id(stages[old]) for key, old in metrics._pending_frontier_stage_batch_ledger_row_keys.items()}
    metrics._transfer_ledger_rows_by_info_id = {
        id(metrics._transfer_info_objects[old_id]): row
        for old_id, row in metrics._transfer_ledger_rows_by_info_id.items()}
    metrics._transfer_info_objects = {id(info): info for info in metrics._transfer_info_objects.values()}
    metrics._config = simulator._config.metrics_config
    metrics._trace_store = simulator._trace_store
    metrics._metrics_ground_truth_trace_path = str(
        Path(metrics._config.output_dir) / metrics._config.metrics_ground_truth_trace_file)
    for role, cluster in simulator._clusters.items():
        backend = cluster.cc_backend
        backend._runner_out_dir = str(output / "cc_cache" / role.name.lower())
        Path(backend._runner_out_dir).mkdir(parents=True, exist_ok=True)
        backend._config.cache_dir = str(output / "cc_cache")
        backend._config.runner_out_dir = backend._runner_out_dir
    for predictor in simulator._predictors.values():
        predictor._cache_dir = str(output / "model_cache")
        predictor._model_manager._cache_dir = predictor._cache_dir
    from frontier.types import EventType
    last_event = simulator._event_trace[-1]
    at_boundary = (last_event["event_type"] == EventType.GLOBAL_BATCH_END.value
                   and simulator._all_requests[0].num_emitted_decode_tokens > 0)
    return {"counter_snapshot": True, "iteration_boundary": at_boundary,
            "pending_ledger_objects_rebound": len(metrics._pending_frontier_stage_batch_ledger_rows)}


def instrument_boundaries(simulator, audit):
    """Observe inclusive production boundaries; never replace their results."""
    from frontier.execution_time_predictor.sklearn_disaggregation_execution_time_predictor import SklearnDisaggregationExecutionTimePredictor
    from frontier.execution_time_predictor.sklearn_moe_execution_time_predictor import SklearnMoEExecutionTimePredictor
    from frontier.cc_backend.backends.collective_sim_cc_backend import CollectiveSimCCBackend
    from frontier.metrics.metrics_store import MetricsStore

    totals = {}
    patches = []
    truth = {"ffn_queries": 0, "attention_queries": 0, "sha256": hashlib.sha256(),
             "roles": Counter(), "layers": Counter(), "measurement_types": Counter(),
             "precisions": Counter(), "model_hashes": set()}
    roles = {id(p): role.name for role, p in simulator._predictors.items()}
    original_loads = json.loads
    markers = {getattr(model, "_frontier_measurement_identity", None)
               for model in simulator._execution_time_prediction_model_manager._diagnostic_models.values()}

    def measured_identity_loads(value, *args, **kwargs):
        if not isinstance(value, str) or value not in markers:
            return original_loads(value, *args, **kwargs)
        start = time.perf_counter()
        try:
            return original_loads(value, *args, **kwargs)
        finally:
            row = totals.setdefault("measurement_identity_json/shared", {"calls": 0, "wall_s": 0.0})
            row["calls"] += 1
            row["wall_s"] += time.perf_counter() - start

    context = patch.object(json, "loads", measured_identity_loads)
    context.start()
    patches.append(context)

    def record(row):
        truth["sha256"].update(json.dumps(row, sort_keys=True).encode())
        truth["sha256"].update(b"\n")
        truth["roles"][row["role"]] += 1
        truth["layers"][row["layer"]] += 1
        truth["measurement_types"][row["measurement"]] += 1
        truth["model_hashes"].update((row["duration_model_hash"], row["kernel_count_model_hash"]))

    def verify_ffn(predictor, args, result):
        name, features = args
        cost = predictor._step5_ffn_costs[name]
        duration_model = predictor._model_manager._diagnostic_models[cost["duration_model_hash"]]
        count_model = predictor._model_manager._diagnostic_models[cost["kernel_count_model_hash"]]
        key = tuple(float(features[n]) for n in duration_model._frontier_feature_names)
        assert result == cost["duration_ms"] == duration_model._frontier_exact_lookup[key]
        assert cost["kernel_count"] == count_model._frontier_exact_lookup[key]
        assert cost["evidence_kind"] == json.loads(duration_model._frontier_measurement_identity)["evidence_kind"]
        assert cost["exact_lookup"]
        truth["ffn_queries"] += 1
        truth["precisions"][cost["precision"]] += 1
        record({"role": roles[id(predictor)], "operator": name, "features": features,
                "layer": cost["global_layer_id"], "measurement": cost["measurement_type"],
                **cost})

    def verify_attention(predictor, args, kwargs, result):
        from frontier.execution_time_predictor.step5_cost import step5_batch_features
        from frontier.execution_time_predictor.step5 import STEP5_FEATURE_COLUMNS

        features, _ = step5_batch_features(predictor, kwargs["batch"], kwargs["layer_id"])
        key = tuple(features[n] for n in STEP5_FEATURE_COLUMNS)
        costs = result.operator_times.costs
        for name, cost in costs.items():
            duration_model = predictor._model_manager._diagnostic_models[cost.duration_model_hash]
            count_model = predictor._model_manager._diagnostic_models[cost.kernel_count_model_hash]
            assert cost.duration_ms == result.operator_times.op_times[name] == duration_model._frontier_exact_lookup[key]
            assert cost.kernel_count == count_model._frontier_exact_lookup[key]
            assert cost.exact_lookup
            assert cost.evidence_kind == json.loads(duration_model._frontier_measurement_identity)["evidence_kind"]
            truth["attention_queries"] += 1
            record({"role": roles[id(predictor)], "operator": name, "features": features,
                    "layer": kwargs["layer_id"], "measurement": cost.measurement_type.value,
                    "duration_model_hash": cost.duration_model_hash,
                    "kernel_count_model_hash": cost.kernel_count_model_hash,
                    "duration_ms": cost.duration_ms, "kernel_count": cost.kernel_count,
                    "evidence_kind": cost.evidence_kind, "exact_lookup": cost.exact_lookup})

    def observe(cls, name, label):
        original = getattr(cls, name)

        def measured(self, *args, **kwargs):
            role = roles.get(id(self), kwargs.get("cluster_type", "shared"))
            if label == "backend":
                role = next(role.name for role, cluster in simulator._clusters.items() if cluster.cc_backend is self)
            key = f"{label}/{role}"
            start = time.perf_counter()
            try:
                result = original(self, *args, **kwargs)
            finally:
                row = totals.setdefault(key, {"calls": 0, "wall_s": 0.0})
                row["calls"] += 1
                row["wall_s"] += time.perf_counter() - start
            if audit and label == "ffn_operator":
                verify_ffn(self, args, result)
            if audit and label == "attention":
                verify_attention(self, args, kwargs, result)
            return result

        context = patch.object(cls, name, measured)
        context.start()
        patches.append(context)

    observe(SklearnDisaggregationExecutionTimePredictor, "predict_stage_execution_time", "public_stage")
    observe(SklearnMoEExecutionTimePredictor, "_predict_attention_layer_time_with_query_cache", "attention")
    observe(SklearnMoEExecutionTimePredictor, "_predict_step5_ffn_operator", "ffn_operator")
    observe(CollectiveSimCCBackend, "_predict", "backend")
    for name in ("on_ep_wave_schedule", "on_replica_stage_schedule", "on_batch_stage_end"):
        observe(MetricsStore, name, "metrics_" + name)
    return totals, patches, truth


def original_boundaries(actual, mode):
    rows = {}
    with (actual / mode / "scheduler.jsonl").open() as stream:
        for line in stream:
            row = json.loads(line)
            if row["event"] not in ("grouped_cache_batch", "grouped_cache_batch_end"):
                continue
            if row["iteration_id"] > 4:
                continue
            key = (row["event"], row["cluster_type"], row["iteration_id"])
            rows[key] = {name: row.get(name) for name in
                         ("event", "cluster_type", "iteration_id", "simulation_time", "num_tokens")}
    return rows


def compare_boundaries(path, expected):
    matched = []
    with path.open() as stream:
        for line in stream:
            row = json.loads(line)
            if row["event"] not in ("grouped_cache_batch", "grouped_cache_batch_end"):
                continue
            key = (row["event"], row["cluster_type"], row["iteration_id"])
            normalized = {name: row.get(name) for name in
                          ("event", "cluster_type", "iteration_id", "simulation_time", "num_tokens")}
            assert normalized == expected[key], (normalized, expected[key])
            matched.append(normalized)
    return matched


def trace_truth(path):
    rows = 0
    roles = Counter()
    layers = set()
    with path.open() as stream:
        for line in stream:
            row = json.loads(line)
            if "type" not in row:
                continue
            assert math.isfinite(row["duration_ms"]) and row["duration_ms"] >= 0
            assert row["cluster"] in ("PREFILL", "DECODE")
            roles[row["cluster"]] += 1
            layers.update(row.get("meta", {}).get("global_layer_ids", ()))
            rows += 1
    assert rows and len(layers) == 92
    return {"rows": rows, "bytes": path.stat().st_size, "roles": roles,
            "layers": sorted(layers), "finite_durations": True}


def digest(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def bundles(source, read_profile):
    selected = {}
    for path in sorted(source.glob("bundle_*.json")):
        bundle = json.loads(path.read_text())
        identity = bundle["identity"]
        if identity.get("input_bindings", {}).get("nixl_read_profile", {}).get("path") != read_profile:
            continue
        roots = [entry for entry in bundle["models"].values()
                 if entry.get("cache_model_name") == "step5_layer_e2e"]
        if not roots or not all(binding["shape_policy"].get("max_tokens_in_batch") == 8192
                                for binding in roots[0]["measurement_identity"]["attention_inputs"]):
            continue
        key = (identity["role"].lower(), identity["coverage"]["measurement_type"])
        assert key not in selected
        selected[key] = (path, bundle)
    assert set(selected) == {(role, family) for role in ("prefill", "decode")
                             for family in ("CUDA_EVENT", "KERNEL_ONLY")}
    return selected


def manager_from_bundles(manager, clusters, metrics, selected, copied):
    """Restore canonical production registries, while refusing initialization fits."""
    from frontier.types import ClusterType

    manager._cluster_configs = clusters
    manager._metrics_config = metrics
    manager._cache_dir = metrics.cache_dir
    manager._all_dummy_mode = False
    manager._two_stream_eager_clusters = frozenset()
    manager._gdn_predictors = {}
    manager._step5_model_bundles = {}
    manager._attention_tp_warning_cache = set()
    for family in ("eager", "device_event", "kernel_only"):
        for prefix in ("_trained_models_", "_models_by_precision_", "_model_profiling_precision_"):
            setattr(manager, prefix + family, {})
        for prefix in ("_trained_models_", "_models_by_precision_"):
            setattr(manager, prefix + family + "_by_contract", {})
    loaded = {}
    for (role_name, method), (path, manifest) in selected.items():
        role = ClusterType.PREFILL if role_name == "prefill" else ClusterType.DECODE
        family = "eager" if method == "CUDA_EVENT" else "kernel_only"
        models = manager.load_model_bundle(Path(metrics.cache_dir) / path.name, manifest["identity"])
        for label, model in models.items():
            entry = manifest["models"][label]
            # Shared artifact identity, exactly as the original manager's union.
            model = loaded.setdefault(entry["sha256"], model)
            identity = entry["typed_identity"]
            name = entry.get("cache_model_name", label)
            registration = manifest["identity"]["registrations"][label]
            precision = registration["precision"]
            if identity is None:
                getattr(manager, "_trained_models_" + family)[name] = model
                getattr(manager, "_models_by_precision_" + family).setdefault(precision, {})[name] = model
            else:
                getattr(manager, "_trained_models_" + family + "_by_contract")[(name, identity)] = model
                getattr(manager, "_models_by_precision_" + family + "_by_contract").setdefault(precision, {})[(name, identity)] = model
        manager._step5_model_bundles.setdefault(role, {})[family] = manifest
    manager._trained_models = {}
    manager._models_by_precision = {}
    manager._model_profiling_precision = {}
    manager._diagnostic_models = {model._frontier_model_hash: model for model in loaded.values()}
    copied.extend({"bundle": str(path), "bundle_id": manifest["bundle_id"],
                   "role": role, "measurement": method, "models": len(manifest["models"])}
                  for (role, method), (path, manifest) in selected.items())


def backend_snapshot(simulator):
    return {role.name: {"config": vars(cluster.cc_backend._config),
                        "entries": [{"key": key, "value": value}
                                    for key, value in cluster.cc_backend._prediction_cache.items()]}
            for role, cluster in simulator._clusters.items()}


def restore_backend(simulator, path):
    saved = json.loads(path.read_text())
    for role, cluster in simulator._clusters.items():
        backend = cluster.cc_backend
        source = saved[role.name]
        old = {k: v for k, v in source["config"].items() if k not in ("cache_dir", "runner_out_dir")}
        new = {k: v for k, v in vars(backend._config).items() if k not in ("cache_dir", "runner_out_dir")}
        assert old == new
        for entry in source["entries"]:
            kind, size, domain, ranks, dims = entry["key"]
            backend._set_cached_prediction((kind, size, domain, tuple(ranks), tuple(dims)), entry["value"])


def main(args):
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    os.environ["FRONTIER_VLLM_V1_SCHED_DECISION_LOG_PATH"] = str(output / "scheduler.jsonl")
    sys.path.insert(0, str(args.collective_root / "python"))
    from frontier.config import SimulationConfig
    from frontier.execution_time_predictor.shared_prediction_model_manager import ExecutionTimePredictionModelManager
    from frontier.cc_backend.backends.collective_sim_cc_backend import CollectiveSimCCBackend
    from frontier.simulator import Simulator
    from frontier.utils.random import set_seeds
    from frontier.config.utils import dataclass_to_dict

    setup_start = time.perf_counter()
    command = json.loads((args.actual / args.mode / "command.json").read_text())
    source_cache = Path(command[command.index("--metrics_config_cache_dir") + 1])
    read_profile = command[command.index("--random_forrest_execution_time_predictor_config_nixl_read_profile") + 1]
    selected = bundles(source_cache, read_profile)
    cache = output / "model_cache"
    cache.mkdir()
    artifacts = {}
    for path, manifest in selected.values():
        shutil.copyfile(path, cache / path.name)
        for entry in manifest["models"].values():
            source = source_cache / entry["artifact"]
            if source.name in artifacts:
                continue
            assert digest(source) == entry["sha256"]
            shutil.copyfile(source, cache / source.name)
            assert digest(cache / source.name) == entry["sha256"]
            artifacts[source.name] = {"source": str(source), "sha256": entry["sha256"],
                                      "bytes": source.stat().st_size}
    argv = command[command.index("frontier.main") + 1:]
    for option, value in (("--metrics_config_output_dir", str(output / "metrics")),
                          ("--metrics_config_cache_dir", str(cache)),
                          ("--collective_sim_cc_backend_config_cache_dir", str(output / "cc_cache"))):
        argv[argv.index(option) + 1] = value
    if args.op_trace:
        argv[argv.index("--no-metrics_config_enable_op_level_tracing")] = "--metrics_config_enable_op_level_tracing"
    with patch.object(sys, "argv", [str(Path(__file__))] + argv):
        config = SimulationConfig.create_from_cli_args()
    set_seeds(config.seed)
    original_config = next((args.actual / args.mode / "metrics").glob("**/config.json"))
    recorded = json.loads(original_config.read_text())
    assert json.loads(json.dumps(dataclass_to_dict(config.cluster_config.replica_config.model_config))) == recorded["cluster_config"]["replica_config"]["model_config"]
    assert not config.enable_parallel_clusters
    assert not config.enable_cluster_event_logging and not config.metrics_config.enable_chrome_trace
    copied = []

    def initialize(manager, clusters, metrics):
        manager_from_bundles(manager, clusters, metrics, selected, copied)

    # Reuse an existing built submodule, redirecting every runner write to scratch.
    with patch.object(ExecutionTimePredictionModelManager, "__init__", initialize), patch.object(
            CollectiveSimCCBackend, "_resolve_collective_sim_repo_root", lambda _: args.collective_root):
        simulator = Simulator(config)
    if args.backend_cache:
        restore_backend(simulator, args.backend_cache)
    state_identity = None
    if args.resume_state:
        state_identity = load_state(simulator, args.resume_state, output)
    setup_s = time.perf_counter() - setup_start
    (output / "setup.json").write_text(json.dumps({"seconds": setup_s, "artifacts": artifacts,
                                                  "bundles": copied}, indent=2))
    rows = []
    request = simulator._all_requests[0]
    assert (request.num_prefill_tokens, request.num_decode_tokens) == (6144, 1024)
    assert request.num_emitted_decode_tokens == args.start_emitted
    profiler = cProfile.Profile()
    expected = original_boundaries(args.actual, args.mode)
    totals, boundary_patches, truth = instrument_boundaries(simulator, args.audit)
    backend_before = {role.name: cluster.cc_backend.get_prediction_cache_stats().copy()
                      for role, cluster in simulator._clusters.items()}
    ledger_before = len(simulator._metric_store._frontier_ep_wave_lane_ledger_rows)
    ledger_path = Path(simulator._metric_store._frontier_ep_wave_lane_ledger_rows._path)
    ledger_position = ledger_path.stat().st_size if ledger_before else 0
    stage_ledger_before = len(simulator._metric_store._frontier_stage_batch_ledger_rows)
    start = time.perf_counter()
    if args.profile:
        profiler.enable()
    emitted = args.start_emitted
    while simulator._event_queue and emitted < args.outputs:
        import heapq
        _, event = heapq.heappop(simulator._event_queue)
        simulator._set_time(event._time)
        event_start = time.perf_counter()
        before = emitted
        new_events = event.handle_event(simulator._global_scheduler, simulator._metric_store)
        simulator._add_events(new_events)
        if config.metrics_config.write_json_trace:
            simulator._event_trace.append(event.to_dict())
        simulator._maybe_export_sequential_checkpoint()
        batch = getattr(event, "_batch", None)
        if batch is not None and str(getattr(event, "_cluster_type", "")) == "decode":
            emitted = max([emitted] + [req.num_emitted_decode_tokens for req in batch.requests])
        rows.append({"event": type(event).__name__, "role": str(getattr(event, "_cluster_type", "shared")),
                      "wall_s": time.perf_counter() - event_start,
                      "simulation_time": simulator._time, "emitted_before": before,
                      "emitted_after": emitted})
        # Bounded cold setup may stop at an event boundary, never canceling a query.
        if time.perf_counter() - start >= args.max_runtime:
            break
    if args.profile:
        profiler.disable()
        profiler.dump_stats(str(output / "iteration.pstats"))
        stream = io.StringIO()
        pstats.Stats(profiler, stream=stream).sort_stats("cumulative").print_stats(40)
        (output / "profile.txt").write_text(stream.getvalue())
    wall_s = time.perf_counter() - start
    for context in reversed(boundary_patches):
        context.stop()
    truth["sha256"] = truth["sha256"].hexdigest()
    truth["model_hashes"] = sorted(truth["model_hashes"])
    (output / "source_truth.json").write_text(json.dumps(truth, indent=2))
